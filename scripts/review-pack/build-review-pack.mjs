#!/usr/bin/env node
/**
 * Builds the Kinora app-review pack: a small library of rights-free demo media laid out the way Kinora scans it,
 * plus the files the review server needs, zipped as dist/kinora-review-pack-<version>.zip.
 *
 *   npm run review-pack                       # = node scripts/review-pack/build-review-pack.mjs
 *   node scripts/review-pack/build-review-pack.mjs --work=/tmp/kinora-pack   # keep and reuse the work folder
 *   node scripts/review-pack/build-review-pack.mjs --with-open-movies         # also fetch Big Buck Bunny (CC BY 3.0)
 *   node scripts/review-pack/build-review-pack.mjs --no-zip                   # leave the folder, skip the zip
 *
 * Content (see lib/catalog.mjs, downloads.json and docs/store/CREDITS.md):
 *   - generated by this script and dedicated to the public domain (CC0 1.0) by the Kinora project:
 *     4 short films (480p, 720p, 1080p with subtitles, 4K HDR10 with 5.1), a 3-episode TV series, a 4-track album
 *     (synthesiser vendored from OpenDJ), an audiobook and a 2-episode podcast (eSpeak NG voices), 9 photos,
 *     2 live test channels with a guide, and all artwork;
 *   - downloaded: 3 CC0 music tracks from the Free Music Archive, checked against the SHA-256 in downloads.json.
 *
 * Needs: ffmpeg with libx264 and libx265, espeak-ng, zip, and the `playwright` package with Chromium (or
 * CHROMIUM_PATH). Takes 15–30 minutes on a 4-core machine (most of it is the 4K HDR film).
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as A from './lib/art.mjs';
import { MOVIES, SHOW, ALBUM, AUDIOBOOK, PODCAST, PHOTOS, CHANNELS } from './lib/catalog.mjs';
import { ff, probe, makeFilm, makeChannelLoop, synthWav, speak, speechMp3, encodeTrack, retagMp3, FFMPEG, ESPEAK } from './lib/media.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const arg = (k) => {
  const a = process.argv.find((x) => x === `--${k}` || x.startsWith(`--${k}=`));
  return a == null ? null : a.includes('=') ? a.slice(a.indexOf('=') + 1) : true;
};
const t0 = Date.now();
const log = (m) => console.log(`[${((Date.now() - t0) / 1000).toFixed(0).padStart(4)}s] ${m}`);
const version = String(arg('version') ?? JSON.parse(fs.readFileSync(path.join(repo, 'package.json'), 'utf8')).version);
const safe = (s) => s.replace(/[\\/:*?"<>|]/g, '');
const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
export const sha256File = (f) => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');

function need(cmd, args, hint) {
  const r = spawnSync(cmd, args, { encoding: 'utf8' });
  if (r.error || r.status !== 0) throw new Error(`${cmd} is needed: ${hint}`);
  return r.stdout + r.stderr;
}

async function pool(items, n, fn) {
  const queue = [...items];
  await Promise.all(Array.from({ length: n }, async () => {
    while (queue.length) await fn(queue.shift());
  }));
}

/** Download `d.url` to `dest` and check its SHA-256; a pinned hash that differs is an error. */
export async function fetchVerified(d, dest, { cache } = {}) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const cached = cache && path.join(cache, `${d.id}${path.extname(new URL(d.url).pathname)}`);
  if (cached && fs.existsSync(cached) && (!d.sha256 || sha256File(cached) === d.sha256)) {
    fs.copyFileSync(cached, dest);
  } else {
    // curl honours HTTPS_PROXY and the system CA store, which Node's fetch does not everywhere.
    const r = spawnSync('curl', ['-sSfL', '--retry', '3', '--max-time', '1800', '-o', dest, d.url], { stdio: ['ignore', 'ignore', 'pipe'], encoding: 'utf8' });
    if (r.status !== 0) throw new Error(`Download failed for ${d.id} (${d.url}): ${r.stderr.trim()}`);
    if (cached) fs.copyFileSync(dest, cached);
  }
  const got = sha256File(dest);
  if (d.sha256 && got !== d.sha256) {
    fs.rmSync(dest, { force: true });
    throw new Error(`SHA-256 mismatch for ${d.id}: expected ${d.sha256}, got ${got}. The file at ${d.url} changed; check the licence on ${d.page} again before updating downloads.json.`);
  }
  return got;
}

function movieNfo(m) {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<movie>
  <title>${xml(m.title)}</title>
  <year>${m.year}</year>
  <premiered>${m.year}-06-01</premiered>
  <tagline>${xml(m.tagline)}</tagline>
  <plot>${xml(m.plot)}</plot>
  <runtime>${Math.max(1, Math.round(m.seconds / 60))}</runtime>
  <mpaa>${m.mpaa}</mpaa>
  <ratings><rating name="default" max="10" default="true"><value>${m.rating}</value></rating></ratings>
${m.genres.map((g) => `  <genre>${xml(g)}</genre>`).join('\n')}
  <studio>Kinora Generated</studio>
</movie>
`;
}

const srtTime = (s) => {
  const ms = Math.round(s * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor((ms % 3600000) / 60000))}:${p(Math.floor((ms % 60000) / 1000))},${p(ms % 1000, 3)}`;
};
export const srt = (cues) => cues.map(([a, b, text], i) => `${i + 1}\n${srtTime(a)} --> ${srtTime(b)}\n${text}\n`).join('\n');

async function main() {
  need(FFMPEG, ['-hide_banner', '-version'], 'install ffmpeg (with libx264/libx265), or set KINORA_FFMPEG');
  const enc = need(FFMPEG, ['-hide_banner', '-encoders'], '');
  for (const e of ['libx264', 'libx265', 'libmp3lame']) if (!enc.includes(e)) throw new Error(`ffmpeg lacks ${e}`);
  need(ESPEAK, ['--version'], 'install eSpeak NG (apt install espeak-ng, brew install espeak-ng), or set ESPEAK');
  if (!arg('no-zip')) need('zip', ['-v'], 'install zip, or pass --no-zip');
  const downloads = JSON.parse(fs.readFileSync(path.join(here, 'downloads.json'), 'utf8'));

  const work = path.resolve(String(arg('work') ?? path.join(os.tmpdir(), 'kinora-review-pack-work')));
  const name = `kinora-review-pack-${version}`;
  const root = path.join(work, name);
  const tmp = path.join(work, 'tmp');
  const cache = path.join(work, 'downloads');
  if (arg('force')) fs.rmSync(root, { recursive: true, force: true });
  for (const d of [root, tmp, cache]) fs.mkdirSync(d, { recursive: true });
  const lib = (...p) => path.join(root, 'library', ...p);
  const done = (f) => fs.existsSync(f) && fs.statSync(f).size > 0;
  log(`Building ${name} in ${root}`);

  const browser = await A.launchBrowser();
  const R = new A.Renderer(browser);
  await R.open();
  const jobs = [];
  const sources = {}; // relative path → { source, licence, ... } for the manifest

  // ---------------------------------------------------------------- movies
  for (const m of MOVIES) {
    const folder = `${safe(m.title)} (${m.year})`;
    const dir = lib('Movies', folder);
    const file = path.join(dir, `${folder}.mp4`);
    await R.render(A.posterHtml(m, { badge: m.badge }), 1000, 1500, path.join(dir, 'poster.jpg'));
    await R.render(A.backdropHtml(m), 1920, 1080, path.join(dir, 'fanart.jpg'));
    fs.writeFileSync(path.join(dir, 'movie.nfo'), movieNfo(m));
    if (m.subtitles) fs.writeFileSync(path.join(dir, `${folder}.en.srt`), srt(m.subtitles));
    const title = path.join(tmp, `${m.slug}-title.png`);
    await R.render(A.titleCardHtml(repo, m.title, m.badge ? `${m.badge} · ${m.tagline}` : m.tagline, 1920, 1080), 1920, 1080, title);
    if (!done(file)) {
      jobs.push({ heavy: m.codec === 'hevc-hdr10', label: m.title, run: async () => {
        const wav = m.music ? synthWav({ ...m.music, artist: 'Kinora', title: m.title }, path.join(tmp, `${m.slug}.wav`)).file : null;
        await makeFilm({ out: file, w: m.w, h: m.h, fps: m.fps, seconds: m.seconds, visual: m.visual, titlePng: title, audioWav: wav, codec: m.codec, surround: m.surround, tmp });
        if (wav) fs.rmSync(wav, { force: true });
      } });
    }
  }

  // ---------------------------------------------------------------- TV show
  {
    const s = SHOW;
    const dir = lib('TV', `${safe(s.title)} (${s.year})`);
    await R.render(A.posterHtml(s), 1000, 1500, path.join(dir, 'poster.jpg'));
    await R.render(A.backdropHtml(s), 1920, 1080, path.join(dir, 'fanart.jpg'));
    await R.render(A.posterHtml({ ...s, slug: `${s.slug}-s1`, tagline: 'Season 1' }), 1000, 1500, path.join(dir, 'season01-poster.jpg'));
    fs.writeFileSync(path.join(dir, 'tvshow.nfo'), `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<tvshow>
  <title>${xml(s.title)}</title>
  <year>${s.year}</year>
  <premiered>${s.year}-09-14</premiered>
  <tagline>${xml(s.tagline)}</tagline>
  <plot>${xml(s.plot)}</plot>
  <mpaa>${s.mpaa}</mpaa>
  <ratings><rating name="default" max="10" default="true"><value>${s.rating}</value></rating></ratings>
${s.genres.map((g) => `  <genre>${xml(g)}</genre>`).join('\n')}
  <studio>${xml(s.studio)}</studio>
</tvshow>
`);
    const sdir = path.join(dir, 'Season 01');
    fs.mkdirSync(sdir, { recursive: true });
    for (const e of s.episodes) {
      const base = `${safe(s.title)} - S01E0${e.n} - ${safe(e.title)}`;
      const file = path.join(sdir, `${base}.mp4`);
      const aired = new Date(Date.UTC(s.year, 8, 14 + (e.n - 1) * 7)).toISOString().slice(0, 10);
      fs.writeFileSync(path.join(sdir, `${base}.nfo`), `<?xml version="1.0" encoding="UTF-8"?>\n<episodedetails>\n  <title>${xml(e.title)}</title>\n  <showtitle>${xml(s.title)}</showtitle>\n  <season>1</season>\n  <episode>${e.n}</episode>\n  <plot>${xml(e.plot)}</plot>\n  <aired>${aired}</aired>\n  <runtime>${Math.max(1, Math.round(e.seconds / 60))}</runtime>\n</episodedetails>\n`);
      const title = path.join(tmp, `${s.slug}-${e.n}-title.png`);
      await R.render(A.titleCardHtml(repo, s.title, `Episode ${e.n}: ${e.title}`, s.w, s.h), s.w, s.h, title);
      const thumb = path.join(sdir, `${base}-thumb.jpg`);
      if (!done(file) || !done(thumb)) {
        jobs.push({ label: `${s.title} E${e.n}`, run: async () => {
          if (!done(file)) {
            const wav = synthWav({ ...e.music, artist: 'Kinora', title: e.title }, path.join(tmp, `${s.slug}-${e.n}.wav`)).file;
            await makeFilm({ out: file, w: s.w, h: s.h, fps: s.fps, seconds: e.seconds, visual: e.visual, titlePng: title, audioWav: wav, tmp });
            fs.rmSync(wav, { force: true });
          }
          await ff(['-ss', String(Math.round(e.seconds * 0.4)), '-i', file, '-frames:v', '1', '-q:v', '3', thumb]);
        } });
      }
    }
  }

  // ---------------------------------------------------------------- music: generated album
  {
    const a = ALBUM;
    const dir = lib('Music', safe(a.artist), safe(a.album));
    const cover = path.join(dir, 'cover.jpg');
    await R.render(A.coverHtml(a, a.album, a.artist), 1000, 1000, cover);
    await R.render(A.coverHtml({ ...a, motif: 'waves' }, a.artist, 'Generated by Kinora'), 1000, 1000, path.join(lib('Music', safe(a.artist)), 'folder.jpg'));
    a.tracks.forEach((t, i) => {
      const out = path.join(dir, `${String(i + 1).padStart(2, '0')} - ${safe(t.title)}.mp3`);
      if (done(out)) return;
      jobs.push({ label: t.title, run: async () => {
        const wav = synthWav({ ...t, artist: a.artist }, path.join(tmp, `track-${i}.wav`)).file;
        await encodeTrack({ wav, cover, out, tags: { title: t.title, artist: a.artist, album_artist: a.artist, album: a.album, track: `${i + 1}/${a.tracks.length}`, date: String(a.year), genre: a.genre, TBPM: String(t.bpm), comment: 'Generated by the Kinora review pack (synthesiser from OpenDJ). CC0 1.0.', copyright: 'CC0 1.0 (public domain dedication)' } });
        fs.rmSync(wav, { force: true });
      } });
    });
  }

  // ---------------------------------------------------------------- music: downloaded CC0 tracks
  for (const d of downloads.core) {
    const dest = path.join(root, d.dest);
    const raw = path.join(cache, `${d.id}.verified.mp3`);
    log(`Fetching ${d.artist} – ${d.title} (CC0)…`);
    await fetchVerified(d, raw, { cache });
    const cover = path.join(path.dirname(dest), 'cover.jpg');
    await R.render(A.coverHtml({ motif: 'waves', pal: ['#101820', '#2d4059', '#f6c90e', '#ea5455'] }, d.album.replace(/\s*\(.*\)$/, ''), d.artist), 1000, 1000, cover);
    if (!done(dest)) {
      await retagMp3({ src: raw, cover, out: dest, tags: { title: d.title, artist: d.artist, album_artist: d.artist, album: d.album.replace(/\s*\(.*\)$/, ''), track: String(d.track), genre: 'Lo-fi', comment: `CC0 1.0 – ${d.page}`, copyright: 'CC0 1.0 (public domain dedication)' } });
    }
    sources[path.relative(root, dest)] = { source: d.page, licence: d.licence, downloadedSha256: d.sha256, note: 'audio stream copied unchanged; tags and cover art replaced' };
  }

  // ---------------------------------------------------------------- optional CC BY open movie
  if (arg('with-open-movies')) {
    for (const d of downloads.optional) {
      const dest = path.join(root, d.dest);
      log(`Fetching optional ${d.title} (${d.licence})…`);
      const got = await fetchVerified(d, dest, { cache });
      if (!d.sha256) log(`  ${d.id}: no pinned hash in downloads.json; downloaded file is ${got} (pin it after checking the licence page).`);
      fs.writeFileSync(path.join(path.dirname(dest), 'ATTRIBUTION.txt'), `${d.title} (${d.year})\n${d.credit}\nLicence: ${d.licence} – ${d.licenceUrl}\nSource: ${d.page}\nNot part of the CC0 core set.\n`);
      sources[path.relative(root, dest)] = { source: d.page, licence: d.licence, downloadedSha256: got, credit: d.credit };
    }
  }

  // ---------------------------------------------------------------- photos
  for (const [album, name, motif, pal] of PHOTOS) await R.render(A.photoHtml(motif, pal, name), 2400, 1600, lib('Photos', album, `${name}.jpg`), { quality: 88 });

  // ---------------------------------------------------------------- audiobook
  {
    const b = AUDIOBOOK;
    const dir = lib('Audiobooks', safe(b.author), safe(b.title));
    const cover = path.join(dir, 'cover.jpg');
    await R.render(A.coverHtml(b, b.title, `${b.author} · read by a synthetic voice`), 1000, 1000, cover);
    b.chapters.forEach(([ctitle, text], i) => {
      const out = path.join(dir, `${String(i + 1).padStart(2, '0')} - ${safe(ctitle)}.mp3`);
      if (done(out)) return;
      jobs.push({ label: `Audiobook ch ${i + 1}`, run: async () => {
        const w1 = speak(`Chapter ${i + 1}. ${ctitle}.`, path.join(tmp, `ab-${i}-h.wav`), { voice: b.voice, speed: b.speed - 10 });
        const w2 = speak(text, path.join(tmp, `ab-${i}-t.wav`), { voice: b.voice, speed: b.speed });
        await speechMp3({ parts: [w1, w2], out, gapSeconds: 1, tags: { title: ctitle, album: b.title, artist: b.author, album_artist: b.author, composer: b.narrator, track: `${i + 1}/${b.chapters.length}`, date: String(b.year), genre: 'Audiobook', comment: 'Original story and synthetic narration generated by the Kinora review pack. CC0 1.0.' } });
      } });
    });
  }

  // ---------------------------------------------------------------- podcast (served by the fixtures web server)
  const podDir = path.join(root, 'fixtures', 'podcast');
  {
    const p = PODCAST;
    await R.render(A.coverHtml(p, p.title, 'A demo podcast · generated'), 1400, 1400, path.join(podDir, 'cover.jpg'));
    const bed = path.join(tmp, 'podcast-bed.wav');
    p.episodes.forEach((e) => {
      const out = path.join(podDir, `${p.slug}-${String(e.n).padStart(2, '0')}.mp3`);
      if (done(out)) return;
      jobs.push({ label: `Podcast ep ${e.n}`, run: async () => {
        if (!done(bed)) synthWav({ style: 'hiphop', bpm: 90, key: [3, 'minor'], seed: 503, artist: 'Kinora', title: 'bed' }, bed);
        const parts = e.lines.map(([who, line], i) => speak(line, path.join(tmp, `pod-${e.n}-${i}.wav`), who === 'a' ? { voice: 'en-gb', speed: 155, pitch: 45 } : { voice: 'en-us+f3', speed: 160, pitch: 60 }));
        await speechMp3({ parts, out, bed, tags: { title: e.title, album: p.title, artist: p.author, track: String(e.n), genre: 'Podcast', comment: 'Generated by the Kinora review pack. CC0 1.0.' } });
      } });
    });
  }

  // ---------------------------------------------------------------- live TV test channels
  const liveDir = path.join(root, 'fixtures', 'livetv');
  for (const ch of CHANNELS) {
    await R.render(A.channelLogoHtml(repo, ch), 400, 240, path.join(liveDir, 'logos', `${ch.id}.png`));
    const frame = path.join(tmp, `${ch.id}-frame.jpg`);
    await R.render(A.channelFrameHtml(repo, ch), 1280, 720, frame);
    const out = path.join(liveDir, `${ch.id}.ts`);
    if (!done(out)) jobs.push({ label: ch.name, run: () => makeChannelLoop({ frame, out, visual: ch.visual, toneHz: ch.visual === 'testcard' ? 1000 : 220 }) });
  }
  fs.writeFileSync(path.join(liveDir, 'channels.json'), JSON.stringify(CHANNELS.map(({ id, number, name, group, programmes }) => ({ id, number, name, group, programmes })), null, 2) + '\n');

  await R.close();
  await browser.close();

  // ---------------------------------------------------------------- encode (the 4K film runs alone, the rest 3 at a time)
  log(`Artwork done; encoding ${jobs.length} files…`);
  const heavy = jobs.filter((j) => j.heavy);
  const light = jobs.filter((j) => !j.heavy);
  await Promise.all([
    pool(heavy, 1, async (j) => { const s = Date.now(); await j.run(); log(`  ✓ ${j.label} (${((Date.now() - s) / 1000).toFixed(0)} s)`); }),
    pool(light, Math.max(1, Math.min(3, os.cpus().length - 1)), async (j) => { const s = Date.now(); await j.run(); log(`  ✓ ${j.label} (${((Date.now() - s) / 1000).toFixed(0)} s)`); }),
  ]);

  // podcast show.json (needs the encoded sizes and durations)
  const showJson = { slug: PODCAST.slug, title: PODCAST.title, author: PODCAST.author, description: PODCAST.description, language: PODCAST.language, episodes: PODCAST.episodes.map((e) => {
    const file = `${PODCAST.slug}-${String(e.n).padStart(2, '0')}.mp3`;
    const f = path.join(podDir, file);
    return { n: e.n, title: e.title, date: e.date, description: e.lines.map((l) => l[1]).join(' '), file, bytes: fs.statSync(f).size, seconds: Math.round(Number(probe(f).format.duration)) };
  }) };
  fs.writeFileSync(path.join(podDir, 'show.json'), JSON.stringify(showJson, null, 2) + '\n');

  // ---------------------------------------------------------------- review-server files, docs, licence
  const copy = (from, to) => {
    fs.mkdirSync(path.dirname(path.join(root, to)), { recursive: true });
    fs.copyFileSync(path.join(repo, from), path.join(root, to));
  };
  copy('scripts/review-pack/seed-review-server.mjs', 'tools/seed-review-server.mjs');
  copy('scripts/review-pack/lib/fixtures.mjs', 'tools/lib/fixtures.mjs');
  copy('deploy/review/docker-compose.yml', 'docker-compose.yml');
  copy('deploy/review/env.example', '.env.example');
  copy('deploy/review/Caddyfile', 'Caddyfile');
  copy('docs/APP_REVIEW.md', 'APP_REVIEW.md');
  copy('docs/store/CREDITS.md', 'CREDITS.md');
  fs.writeFileSync(path.join(root, 'LICENSE-CC0.txt'), `Kinora review pack ${version}

Everything in this pack was generated by the Kinora project's build script (scripts/review-pack/ in the Kinora
repository), except the three music tracks listed in CREDITS.md, which their authors released under CC0 1.0.

To the extent possible under law, the Kinora project has waived all copyright and related or neighbouring rights to
the generated films, series, music, audiobook, podcast, photos, test channels and artwork in this pack.
This work is published from: United Kingdom.

  CC0 1.0 Universal: https://creativecommons.org/publicdomain/zero/1.0/legalcode

The Kinora name and logo (in the title cards, channel logos and test channel frames) are Kinora's own branding and
are not part of this dedication. The review-server tools in tools/ are MIT-licensed, like the rest of Kinora.
`);
  fs.writeFileSync(path.join(root, 'README.txt'), `Kinora review pack ${version}

library/    the media, laid out the way Kinora scans it (Movies, TV, Music, Audiobooks, Photos)
fixtures/   the podcast and Live TV test channels, served by the "fixtures" web server
tools/      the seeder that sets up and resets the review server
manifest.json  every file with its size, SHA-256, source and licence

Start the review server: copy .env.example to .env, fill it in, then  docker compose up -d
Full instructions: APP_REVIEW.md   Credits and licences: CREDITS.md, LICENSE-CC0.txt
`);

  // ---------------------------------------------------------------- manifest + checks
  const files = fs.readdirSync(root, { recursive: true }).map(String).filter((f) => fs.statSync(path.join(root, f)).isFile() && f !== 'manifest.json').sort();
  const entries = files.map((f) => {
    const abs = path.join(root, f);
    const s = sources[f] ?? (f.startsWith('tools/') || /\.(md|txt|yml|example)$|Caddyfile$/.test(f) ? { source: 'kinora-repo', licence: f.startsWith('tools/') || /\.yml$|Caddyfile|example/.test(f) ? 'MIT' : 'CC0-1.0' } : { source: 'generated', licence: 'CC0-1.0' });
    return { path: f, bytes: fs.statSync(abs).size, sha256: sha256File(abs), ...s };
  });
  for (const e of entries.filter((x) => /\.(mp4|mp3|ts)$/.test(x.path))) {
    const p = probe(path.join(root, e.path));
    e.durationSeconds = Math.round(Number(p.format.duration));
    const v = p.streams.find((s) => s.codec_type === 'video' && s.width);
    if (v) e.video = `${v.codec_name} ${v.width}x${v.height}${v.color_transfer === 'smpte2084' ? ' HDR10' : ''}`;
    const a = p.streams.find((s) => s.codec_type === 'audio');
    if (a) e.audio = `${a.codec_name} ${a.channels}ch`;
  }
  const manifest = { name, version, builtAt: new Date().toISOString(), tool: 'scripts/review-pack/build-review-pack.mjs', licenceSummary: 'All media CC0 1.0 (generated by the Kinora project, or CC0 tracks listed in CREDITS.md); tools MIT', files: entries };
  fs.writeFileSync(path.join(root, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  const total = entries.reduce((s, e) => s + e.bytes, 0);
  log(`Pack folder: ${root} (${entries.length} files, ${(total / 1048576).toFixed(1)} MB)`);

  if (!arg('no-zip')) {
    const outDir = path.resolve(repo, String(arg('out') ?? 'dist'));
    fs.mkdirSync(outDir, { recursive: true });
    const zipFile = path.join(outDir, `${name}.zip`);
    fs.rmSync(zipFile, { force: true });
    // Media is already compressed: store it, deflate only text.
    const r = spawnSync('zip', ['-r', '-q', '-n', '.mp4:.mp3:.ts:.jpg:.png:.mov', zipFile, name], { cwd: work, stdio: 'inherit' });
    if (r.status !== 0) throw new Error('zip failed');
    fs.writeFileSync(`${zipFile}.sha256`, `${sha256File(zipFile)}  ${path.basename(zipFile)}\n`);
    log(`Zip: ${path.relative(repo, zipFile)} (${(fs.statSync(zipFile).size / 1048576).toFixed(1)} MB), SHA-256 in ${path.basename(zipFile)}.sha256`);
  }
  fs.rmSync(tmp, { recursive: true, force: true });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().catch((e) => {
    console.error(e.stack || e.message);
    process.exit(1);
  });
}
