/**
 * Builds the service worker (dist/sw.js) and the offline page (dist/offline.html + offline.js) at the end of
 * `vite build`. No dependencies: the worker is web/sw/worker.js with a build version, the precache list and the
 * helpers from web/sw/core.js prepended.
 *
 * The version is a hash of everything the worker serves (file names of the build, index.html, the public files and
 * the worker's own sources), so every build that changes anything gets a new worker and a new cache, and the old
 * cache is deleted when it activates.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin, ResolvedConfig } from 'vite';
// Plain JS shared with the worker (types in core.d.ts; unit-tested in web/test/sw.test.ts).
import { precacheList } from './core.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (f: string) => fs.readFileSync(path.join(here, f), 'utf8');

function walk(dir: string, rel = ''): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name), `${rel}${e.name}/`) : [`${rel}${e.name}`]));
}

export function serviceWorker(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'mediamax:service-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(c) {
      config = c;
    },
    generateBundle(_options, bundle) {
      const base = config.base.endsWith('/') ? config.base : `${config.base}/`;
      const index = bundle['index.html'];
      const html = index && index.type === 'asset' ? String(index.source) : '';
      // Files index.html loads at startup (entry script, CSS, modulepreloads), relative to the base path.
      const entryAssets = [...html.matchAll(/(?:src|href)="([^"]+)"/g)].map((m) => m[1]).filter((u) => u.startsWith(base)).map((u) => u.slice(base.length));
      const publicDir = config.publicDir;
      const publicFiles = publicDir ? walk(publicDir) : [];
      const precache: string[] = precacheList({ entryAssets, publicFiles });

      const sources = { core: read('core.js'), worker: read('worker.js'), page: read('offline.html'), script: read('offline.js') };
      const hash = crypto.createHash('sha256');
      for (const s of Object.values(sources)) hash.update(s);
      hash.update(html);
      hash.update(Object.keys(bundle).sort().join('\n'));
      for (const f of publicFiles.sort()) hash.update(f).update(fs.readFileSync(path.join(publicDir, f)));
      hash.update(base);
      const version = hash.digest('hex').slice(0, 12);

      const sw = [
        `/* MediaMax service worker, build ${version}. Generated by web/sw/plugin.ts; do not edit. */`,
        `const VERSION = ${JSON.stringify(version)};`,
        `const PRECACHE = ${JSON.stringify(precache)};`,
        sources.core.replace(/^export /gm, ''),
        sources.worker,
      ].join('\n');
      const withBase = (s: string) => s.replaceAll('%BASE%', base);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: sw });
      this.emitFile({ type: 'asset', fileName: 'offline.html', source: withBase(sources.page) });
      this.emitFile({ type: 'asset', fileName: 'offline.js', source: withBase(sources.script) });
    },
  };
}
